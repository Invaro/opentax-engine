/**
 * THE single source of truth for inline eval flags <-> corpus fact ids.
 * Option registration (index.ts), fact assembly (eval.ts), and error hints
 * (output.ts) all derive from this table — it cannot drift in one place only.
 * A contract test asserts every corpus fact has an entry.
 */

export interface FactFlag {
  /** Corpus fact id this flag sets. */
  factId: string;
  /** Commander option declaration, e.g. "--wages <dollars>". */
  option: string;
  /** Commander's camelCased property name for this option. */
  key: string;
  /** Help text for --help. */
  help: string;
  /** true = presence flag (sets the fact to a boolean); false = takes a value. */
  boolean: boolean;
  /** For presence flags: the boolean the flag sets (default true). */
  setValue?: boolean;
  /** Help group heading (defaults to "Common situations:"). */
  group?: string;
}

/** Plain-English filing-status aliases -> canonical corpus values. */
const STATUS_ALIASES: Record<string, string> = {
  single: "single",
  mfj: "mfj",
  married: "mfj",
  marriedjoint: "mfj",
  marriedfilingjointly: "mfj",
  joint: "mfj",
  mfs: "mfs",
  marriedseparate: "mfs",
  marriedseparately: "mfs",
  marriedfilingseparately: "mfs",
  separate: "mfs",
  hoh: "hoh",
  headofhousehold: "hoh",
  qss: "qss",
  survivingspouse: "qss",
  qualifyingsurvivingspouse: "qss",
  widow: "qss",
  widower: "qss",
};

/** "Married Filing Jointly" / "head-of-household" / "mfj" all normalize. */
export function normalizeStatus(raw: string): string {
  const key = raw.toLowerCase().replace(/[^a-z]/g, "");
  return STATUS_ALIASES[key] ?? raw;
}

