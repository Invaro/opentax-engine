// first flag per fact wins (a fact may have paired true/false flags, e.g.
// --covered-by-plan / --not-covered-by-plan — hints show the primary one)
const BY_FACT = new Map<string, FactFlag>();
for (const f of FACT_FLAGS) {
  if (!BY_FACT.has(f.factId)) BY_FACT.set(f.factId, f);
}

/** "--status <single|mfj|hoh>"-style hint for a fact id, if a flag exists. */
export function flagFor(factId: string): string | undefined {
  return BY_FACT.get(factId)?.option;
}

/** Assemble facts from parsed commander options, using the table. */
export function factsFromOptions(
  opts: Record<string, unknown>,
): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const f of FACT_FLAGS) {
    const v = opts[f.key];
    if (f.boolean) {
      if (v === true) out[f.factId] = f.setValue ?? true;
    } else if (v !== undefined) {
      let value = v;
      if (typeof v === "string") {
        if (f.factId === "filingStatus" || f.factId === "parentFilingStatus") {
          value = normalizeStatus(v);
        }
        if (f.factId === "occupation") {
          const match = matchOccupation(v);
          if ("slug" in match) value = match.slug;
          else {
            throw new FactValidationError(
              match.candidates.length
                ? `"${v}" matches several listed occupations: ${match.candidates.join(", ")} — pick one`
                : `"${v}" is not on the Treasury Tipped Occupation list — pass one of the listed slugs, or "other" if the job is not listed (run \`opentax facts\` for details)`,
            );
          }
        }
      }
      out[f.factId] = value;
    }
  }
  return out;
}
