#!/usr/bin/env node
/**
 * The library API report and the ID baseline.
 *
 *   node scripts/api-report.mjs            check: report/*.api.md match the built packages
 *   node scripts/api-report.mjs --write    regenerate report/*.api.md
 *   node scripts/api-report.mjs --write-baseline
 *                                          record this tree's contract in baseline.json
 *                                          (run when cutting a release)
 *
 * The report is every export of the four library packages with its tier
 * (surface.json) and its declaration from the built .d.ts, so any change to
 * the surface is a visible diff. Needs `pnpm build` first.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

const here = join(dirname(fileURLToPath(import.meta.url)), "..");
const root = join(here, "../..");
const surface = JSON.parse(readFileSync(join(here, "surface.json"), "utf8"));
export const PACKAGES = {
  "@invaro/opentax-core": "core",
  "@invaro/opentax-corpus-us-federal": "corpus-us-federal",
  "@invaro/opentax-solve": "solve",
  "@invaro/opentax-compose": "compose",
};
const TIERS = ["stable", "provisional", "internal"];

/** name -> { kind, declaration } for every export of a package's built index.d.ts */
export function exportsOf(dir) {
  const entry = join(root, "packages", dir, "dist/index.d.ts");
  if (!existsSync(entry)) throw new Error(`${entry} is missing: run pnpm build first`);
  const program = ts.createProgram([entry], {
    module: ts.ModuleKind.NodeNext,
    moduleResolution: ts.ModuleResolutionKind.NodeNext,
    target: ts.ScriptTarget.ES2022,
    skipLibCheck: true,
    noEmit: true,
  });
  const checker = program.getTypeChecker();
  const moduleSymbol = checker.getSymbolAtLocation(program.getSourceFile(entry));
  const printer = ts.createPrinter({ removeComments: true });
  const out = {};
  for (const exported of checker.getExportsOfModule(moduleSymbol)) {
    const symbol = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
    const declarations = symbol.declarations ?? [];
    const text = declarations
      .map((d) => {
        // a `const x = …` export: print its whole statement so `declare const` and the type show
        const node = ts.isVariableDeclaration(d) ? d.parent.parent : d;
        return printer.printNode(ts.EmitHint.Unspecified, node, node.getSourceFile()).replace(/^export /, "");
      })
      .join("\n");
    const kind = declarations.some((d) => ts.isClassDeclaration(d))
      ? "class"
      : declarations.some((d) => ts.isFunctionDeclaration(d))
        ? "function"
        : declarations.some((d) => ts.isVariableDeclaration(d))
          ? "const"
          : declarations.some((d) => ts.isInterfaceDeclaration(d))
            ? "interface"
            : "type";
    out[exported.name] = { kind, declaration: text };
  }
  return out;
}

export function tierOf(pkg, name) {
  return TIERS.find((t) => surface[pkg]?.[t]?.includes(name));
}

/** every problem with surface.json: an unclassified export, or an entry that no longer exists */
export function surfaceProblems() {
  const problems = [];
  for (const [pkg, dir] of Object.entries(PACKAGES)) {
    const actual = exportsOf(dir);
    const listed = TIERS.flatMap((t) => surface[pkg]?.[t] ?? []);
    for (const name of Object.keys(actual)) {
      if (!listed.includes(name)) problems.push(`${pkg}: export "${name}" has no tier in surface.json`);
    }
    for (const name of listed) {
      if (!(name in actual)) problems.push(`${pkg}: surface.json lists "${name}", which is not exported`);
      if (listed.filter((n) => n === name).length > 1) problems.push(`${pkg}: "${name}" is listed twice in surface.json`);
    }
  }
  return [...new Set(problems)];
}

export function reportFor(pkg) {
  const dir = PACKAGES[pkg];
  const actual = exportsOf(dir);
  const version = JSON.parse(readFileSync(join(root, "packages", dir, "package.json"), "utf8")).version;
  const lines = [
    `# ${pkg} — API report`,
    "",
    "Generated by `packages/library-api/scripts/api-report.mjs --write` from the built `.d.ts`. Do not edit.",
    "A diff here is a change to the package's surface: see docs/LIBRARY-API.md for what each tier promises.",
    "",
  ];
  for (const tier of TIERS) {
    const names = Object.keys(actual).filter((n) => tierOf(pkg, n) === tier).sort((a, b) => a.localeCompare(b));
    if (!names.length) continue;
    lines.push(`## ${tier}`, "");
    for (const name of names) {
      // a very long declaration (a schema's inferred type) is recorded by its hash: a change still shows as a diff
      const decl = actual[name].declaration;
      const long = decl.split("\n").length > 150;
      const shown = long ? `// ${decl.split("\n").length} lines; sha256 ${createHash("sha256").update(decl).digest("hex")}` : decl;
      lines.push(`### ${name} (${actual[name].kind})`, "", "```ts", shown, "```", "");
    }
  }
  return { text: lines.join("\n"), version };
}

/** the corpus's ID contract as of this tree */
/** (the tests pass the source modules; the command line reads the build) */
export async function currentContract(modules = {}) {
  const core = modules.core ?? (await import(pathToFileURL(join(root, "packages/core/dist/index.js")).href));
  const federal = modules.federal ?? (await import(pathToFileURL(join(root, "packages/corpus-us-federal/dist/index.js")).href));
  const corpus = federal.getCorpus();
  const facts = {};
  for (const f of corpus.facts) {
    facts[f.id] = {
      type: f.type,
      ...(f.enumValues ? { enumValues: [...f.enumValues] } : {}),
      ...(f.min !== undefined ? { min: f.min } : {}),
      ...(f.max !== undefined ? { max: f.max } : {}),
      hasDefault: f.default !== undefined,
    };
  }
  const errors = {};
  for (const [name, value] of Object.entries(core)) {
    if (typeof value === "function" && value.prototype instanceof core.OpenTaxError) {
      const sample =
        name === "NeedsFactsError" || name === "CycleError" || name === "CorpusValidationError"
          ? new value([])
          : name === "FactValidationError"
            ? new value("x", "someFact")
            : new value("x", "2025-01-01", []);
      errors[name] = { code: sample.code, data: Object.keys(sample.data()).sort() };
    }
  }
  const ruleOutputs = {};
  const ruleMaxVersion = {};
  for (const [id, versions] of corpus.byId) {
    ruleOutputs[id] = versions[0].output.type;
    ruleMaxVersion[id] = Math.max(...versions.map((v) => v.version));
  }
  const exports = {};
  const versions = {};
  for (const [pkg, dir] of Object.entries(PACKAGES)) {
    const declared = exportsOf(dir);
    const hash = (name) => createHash("sha256").update(declared[name]?.declaration ?? "").digest("hex").slice(0, 16);
    exports[pkg] = {
      stable: Object.fromEntries([...surface[pkg].stable].sort().map((n) => [n, hash(n)])),
      provisional: [...surface[pkg].provisional].sort(),
    };
    versions[pkg] = JSON.parse(readFileSync(join(root, "packages", dir, "package.json"), "utf8")).version;
  }
  const sortKeys = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
  return {
    corpusVersion: corpus.version,
    merkleRoot: corpus.merkleRoot,
    versions,
    facts,
    ruleOutputs: sortKeys(ruleOutputs),
    ruleMaxVersion: sortKeys(ruleMaxVersion),
    ruleHashes: sortKeys(Object.fromEntries(corpus.ruleHashes)),
    extensionPoints: Object.keys(federal.EXTENSION_POINTS).sort(),
    defaultTarget: federal.DEFAULT_TARGET,
    errors,
    exports,
  };
}

const ENTRY = /^\d{4}-\d{2}-\d{2}$/;
/** an entry of deprecations.json: which release announced the break, and when */
function announced(entry) {
  return entry && typeof entry.announcedIn === "string" && ENTRY.test(entry.announcedOn ?? "") && typeof entry.note === "string";
}

/**
 * Everything in `now` that breaks the contract recorded in `baseline`, as
 * { check, items }. A break listed in `allowed` (deprecations.json) with the
 * release and date that announced it is not a violation.
 */
export function contractViolations(baseline, now, allowed) {
  const out = [];
  const add = (check, items) => items.length && out.push({ check, items });
  const ok = (section, key) => announced(allowed[section]?.[key]);
  const big = (x) => BigInt(x);

  const factIds = Object.keys(baseline.facts);
  add("fact id removed", factIds.filter((id) => !(id in now.facts) && !ok("removedFacts", id)));
  const kept = factIds.filter((id) => id in now.facts);
  add("fact retyped", kept.filter((id) => now.facts[id].type !== baseline.facts[id].type && !ok("retypedFacts", id)));
  add(
    "enum value removed",
    kept.flatMap((id) => (baseline.facts[id].enumValues ?? []).filter((v) => !(now.facts[id].enumValues ?? []).includes(v) && !ok("removedEnumValues", `${id}=${v}`)).map((v) => `${id}=${v}`)),
  );
  add("default removed", kept.filter((id) => baseline.facts[id].hasDefault && !now.facts[id].hasDefault && !ok("removedDefaults", id)));
  add(
    "accepted range narrowed",
    kept.filter((id) => {
      const was = baseline.facts[id];
      const is = now.facts[id];
      const minUp = is.min !== undefined && (was.min === undefined || big(is.min) > big(was.min));
      const maxDown = is.max !== undefined && (was.max === undefined || big(is.max) < big(was.max));
      return (minUp || maxDown) && !ok("narrowedRanges", id);
    }),
  );

  const ruleIds = Object.keys(baseline.ruleOutputs);
  add("rule id removed", ruleIds.filter((id) => !(id in now.ruleOutputs) && !ok("removedRuleIds", id)));
  add("rule output type changed", ruleIds.filter((id) => id in now.ruleOutputs && now.ruleOutputs[id] !== baseline.ruleOutputs[id]));
  add("published rule version edited (a change is a new version)", Object.keys(baseline.ruleHashes).filter((k) => k in now.ruleHashes && now.ruleHashes[k] !== baseline.ruleHashes[k]));
  add(
    "new rule version does not have a higher number than every version ever published",
    Object.keys(now.ruleHashes).filter((k) => {
      if (k in baseline.ruleHashes) return false;
      const at = k.lastIndexOf("@");
      const max = baseline.ruleMaxVersion[k.slice(0, at)];
      return max !== undefined && Number(k.slice(at + 1)) <= max;
    }),
  );

  add("extension point removed", baseline.extensionPoints.filter((p) => !now.extensionPoints.includes(p)));
  add("default target changed", now.defaultTarget === baseline.defaultTarget ? [] : [`${baseline.defaultTarget} -> ${now.defaultTarget}`]);
  add(
    "error code or data fields changed",
    Object.keys(baseline.errors).filter((name) => {
      const was = baseline.errors[name];
      const is = now.errors[name];
      return !is || is.code !== was.code || was.data.some((f) => !is.data.includes(f));
    }),
  );

  const major = (v) => Number(String(v).split(".")[0]);
  for (const [pkg, tiers] of Object.entries(baseline.exports)) {
    const is = now.exports[pkg]?.stable ?? {};
    const removed = Object.keys(tiers.stable).filter((n) => !(n in is));
    const changed = Object.keys(tiers.stable).filter((n) => n in is && is[n] !== tiers.stable[n]);
    add(`${pkg}: stable export removed`, removed.filter((n) => !ok("removedStableExports", `${pkg}#${n}`)));
    add(`${pkg}: stable declaration changed (list it in deprecations.json changedStableDeclarations as additive or breaking)`, changed.filter((n) => !ok("changedStableDeclarations", `${pkg}#${n}`)));
    const breaking = [...removed, ...changed.filter((n) => allowed.changedStableDeclarations?.[`${pkg}#${n}`]?.kind === "breaking")];
    // semver: a break of the stable surface needs a new major version (the corpus is versioned by release)
    if (breaking.length && pkg !== "@invaro/opentax-corpus-us-federal" && major(now.versions[pkg]) <= major(baseline.versions[pkg])) {
      add(`${pkg}: breaking change without a new major version (${baseline.versions[pkg]} -> ${now.versions[pkg]})`, breaking);
    }
  }
  for (const [section, entries] of Object.entries(allowed)) {
    if (section.startsWith("$")) continue;
    add(`deprecations.json ${section}: an entry needs announcedIn, announcedOn (YYYY-MM-DD) and note`, Object.keys(entries).filter((k) => !announced(entries[k])));
  }
  return out;
}

/** names of non-stable exports that a stable declaration mentions (a stable signature must not lean on them) */
export function stableLeaks() {
  const leaks = [];
  const tiers = new Map();
  for (const pkg of Object.keys(PACKAGES)) for (const t of TIERS) for (const n of surface[pkg][t]) if (!tiers.has(n) || t === "stable") tiers.set(n, tiers.get(n) === "stable" ? "stable" : t);
  for (const [pkg, dir] of Object.entries(PACKAGES)) {
    const declared = exportsOf(dir);
    for (const name of surface[pkg].stable) {
      for (const word of new Set(declared[name].declaration.match(/\b[A-Z][A-Za-z0-9_]*\b/g) ?? [])) {
        if (word !== name && tiers.has(word) && tiers.get(word) !== "stable") leaks.push(`${pkg}: stable ${name} mentions ${tiers.get(word)} ${word}`);
      }
    }
  }
  return leaks;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2] ?? "--check";
  const problems = surfaceProblems();
  if (problems.length) {
    console.error(problems.join("\n"));
    process.exit(1);
  }
  if (mode === "--write-baseline") {
    const contract = await currentContract();
    const file = join(here, "baseline.json");
    if (existsSync(file)) {
      // rolling forward must not hide a break: the tree has to satisfy the baseline it replaces
      const previous = JSON.parse(readFileSync(file, "utf8"));
      const violations = contractViolations(previous, contract, JSON.parse(readFileSync(join(here, "deprecations.json"), "utf8")));
      if (violations.length && !process.argv.includes("--force")) {
        console.error("this tree breaks the current baseline; fix it or announce it in deprecations.json first:");
        for (const v of violations) console.error(`  ${v.check}: ${v.items.slice(0, 8).join(", ")}${v.items.length > 8 ? ", …" : ""}`);
        process.exit(1);
      }
      // a version number is never reused, even after its version was retired
      for (const [id, max] of Object.entries(previous.ruleMaxVersion ?? {})) {
        if (!(id in contract.ruleMaxVersion) || contract.ruleMaxVersion[id] < max) contract.ruleMaxVersion[id] = max;
      }
    }
    writeFileSync(file, JSON.stringify(contract, null, 1) + "\n");
    console.log(`baseline.json: corpus ${contract.corpusVersion}, ${Object.keys(contract.facts).length} facts, ${Object.keys(contract.ruleOutputs).length} rule ids, ${Object.keys(contract.ruleHashes).length} rule versions`);
  } else {
    let stale = 0;
    for (const pkg of Object.keys(PACKAGES)) {
      const file = join(here, "report", `${PACKAGES[pkg]}.api.md`);
      const { text } = reportFor(pkg);
      if (mode === "--write") writeFileSync(file, text);
      else if (!existsSync(file) || readFileSync(file, "utf8") !== text) {
        stale++;
        console.error(`${file} is stale: run pnpm -F @invaro/opentax-library-api api:report`);
      }
    }
    if (stale) process.exit(1);
    console.log(mode === "--write" ? "wrote report/*.api.md" : "API report is in sync");
  }
}
